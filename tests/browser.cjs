const {chromium}=require('playwright');
const {pathToFileURL}=require('node:url');
const path=require('node:path');
const fs=require('node:fs');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'chrome'});
 const context=await browser.newContext({viewport:{width:1440,height:1080}});
 const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const url=pathToFileURL(path.resolve(__dirname,'../index.html')).href;
 const expected=JSON.parse(fs.readFileSync(path.resolve(__dirname,'../library.json'),'utf8')).items;
 await page.goto(url);await page.waitForSelector('.card');
 await page.evaluate(()=>localStorage.setItem('motion-index-favorites',JSON.stringify(['ui-deleted-entry'])));
 await page.reload();
 assert.equal(await page.locator('#nav-favorites').textContent(),'0','Removed entries must not leave ghost favorite counts');
 assert.equal(await page.locator('.card').count(),Math.min(30,expected.length));
 await page.locator('#search').fill('React 背景');assert.ok(await page.locator('.card').count()>0);
 await page.locator('#platform').selectOption('B站');assert.equal(await page.locator('.card').count(),0);
 assert.ok(await page.locator('#empty').isVisible());
 await page.locator('#random').click();assert.ok(!(await page.locator('#detail').isVisible()));
 await page.locator('#reset').click();
 const firstName=await page.locator('.card h3').first().textContent();
 await page.locator('.favorite-button').first().click();
 await page.locator('[data-view=favorites]').click();assert.equal(await page.locator('.card').count(),1);
 await page.reload();await page.locator('[data-view=favorites]').click();assert.equal(await page.locator('.card').count(),1);
 assert.equal(await page.locator('.card h3').first().textContent(),firstName);
 await page.locator('.card-actions button').first().click();assert.ok(await page.locator('#detail').isVisible());
 await page.keyboard.press('Escape');assert.ok(!(await page.locator('#detail').isVisible()));
 const downloadEvent=page.waitForEvent('download');await page.locator('#export').click();const download=await downloadEvent;
 const stream=await download.createReadStream();let exported='';for await(const chunk of stream)exported+=chunk;
 assert.equal(JSON.parse(exported).items.length,1);
 await page.locator('#reset').click();await page.locator('#platform').selectOption('GitHub');
 const listed=await page.locator('.card').count();assert.ok(listed>0);
 await page.locator('#reset').click();await page.locator('#load-more').click();assert.equal(await page.locator('.card').count(),60);
 await page.locator('[data-view=all]').click();
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:path.resolve(__dirname,'../preview-desktop.png'),fullPage:false});
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:path.resolve(__dirname,'../preview-mobile.png'),fullPage:false});
 await page.setViewportSize({width:320,height:800});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({status:'PASS',items:expected.length,checks:['search','combined filters','empty results','random with no results','favorite persistence','detail dialog','JSON export','GitHub filter','load more','390px and 320px overflow','no JavaScript exceptions']}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
